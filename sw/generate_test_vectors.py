#!/usr/bin/env python3
"""Build sim/golden vectors from weight ROMs for the full UNSW test set.
Writes flattened Q1.7 features + per-sample expected preds so `tb_fnn_top`
can check every test row against the software INT8 reference.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from model.config import GENERATED_DIR, REPO_ROOT, default_config, with_layers
from model.data_unsw import load_unsw, to_q17
from model.quantize import QuantTensors, sw_int_forward


def load_mems(dir_path, cfg) -> QuantTensors:
    """Load concatenated weight/bias .mem files into per-layer INT8 tensors."""
    w_all = np.array(
        [int(x, 16) for x in (dir_path / "weights.mem").read_text().split()],
        dtype=np.uint8,
    ).astype(np.int8)
    b_all = np.array(
        [int(x, 16) for x in (dir_path / "biases.mem").read_text().split()],
        dtype=np.uint8,
    ).astype(np.int8)

    weights = []
    biases = []
    w_off = 0
    b_off = 0
    sizes = cfg.layer_sizes
    for i in range(cfg.num_fc):
        in_d, out_d = sizes[i], sizes[i + 1]
        n_w = out_d * in_d
        weights.append(w_all[w_off : w_off + n_w].reshape(out_d, in_d))
        biases.append(b_all[b_off : b_off + out_d])
        w_off += n_w
        b_off += out_d

    return QuantTensors(
        weights=weights,
        biases=biases,
        weight_scales=[2**-7] * cfg.num_fc,
        act_scale=2**-7,
        frac_bits=cfg.frac_bits,
    )


def cfg_from_meta(dir_path):
    """Recover ModelConfig from export_meta.txt when present."""
    meta = dir_path / "export_meta.txt"
    if not meta.exists():
        return default_config()
    vals = {}
    for line in meta.read_text(encoding="utf-8").splitlines():
        if "=" in line:
            k, v = line.split("=", 1)
            vals[k.strip()] = v.strip()
    if "layer_sizes" in vals:
        raw = vals["layer_sizes"].strip("[]")
        sizes = tuple(int(x.strip()) for x in raw.split(",") if x.strip())
        return with_layers(sizes)
    return default_config()


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--weights-dir",
        type=str,
        default=str(GENERATED_DIR),
        help="Directory with weights.mem / biases.mem (default: weights/generated)",
    )
    ap.add_argument(
        "--limit",
        type=int,
        default=0,
        help="Max test samples (0 = full UNSW test set)",
    )
    args = ap.parse_args()

    src = Path(args.weights_dir)
    if not src.is_absolute():
        src = REPO_ROOT / src

    cfg = cfg_from_meta(src)
    q = load_mems(src, cfg)
    data = load_unsw(cfg, n_features=cfg.input_dim)

    n = len(data.X_test) if args.limit <= 0 else min(args.limit, len(data.X_test))
    feat_lines: list[str] = []
    exp_lines: list[str] = []
    label_lines: list[str] = []
    match_true = 0

    for i in range(n):
        x_q = to_q17(data.X_test[i], cfg.frac_bits)
        true_label = int(data.y_test[i])
        scores, pred = sw_int_forward(q, x_q)
        feat_lines.extend(f"{(int(v) & 0xFF):02X}" for v in x_q)
        exp_lines.append(f"{pred:02X}")
        label_lines.append(f"{true_label:02X}")
        match_true += int(pred == true_label)

    out = REPO_ROOT / "sim" / "golden"
    out.mkdir(parents=True, exist_ok=True)
    (out / "features.mem").write_text("\n".join(feat_lines) + "\n", encoding="utf-8")
    (out / "expected.mem").write_text("\n".join(exp_lines) + "\n", encoding="utf-8")
    (out / "labels.mem").write_text("\n".join(label_lines) + "\n", encoding="utf-8")
    (out / "meta.txt").write_text(
        "\n".join(
            [
                f"n_samples={n}",
                f"input_dim={cfg.input_dim}",
                f"layers={list(cfg.layer_sizes)}",
                f"source=UNSW_test[0:{n}]",
                f"sw_int8_vs_label={match_true / n:.6f}",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    (out / "golden_params.vh").write_text(
        "\n".join(
            [
                "// Auto-generated by generate_test_vectors.py — do not edit.",
                f"`define GOLDEN_N_SAMPLES  {n}",
                f"`define GOLDEN_FEAT_WORDS {n * cfg.input_dim}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    (out / "expected.txt").write_text(
        f"n_samples={n}\nlayers={list(cfg.layer_sizes)}\nsw_int8_vs_label={match_true / n:.6f}\n",
        encoding="utf-8",
    )
    print(
        f"Wrote golden {n} UNSW_test samples "
        f"(sw INT8 vs label={match_true / n:.4f}, layers={cfg.layer_sizes}) from {src}"
    )


if __name__ == "__main__":
    main()

"""Emit .mem ROMs and regenerate rtl/include/fnn_params.vh for arbitrary depth."""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from .config import (
    PARAMS_VH,
    ModelConfig,
    default_config,
)
from .quantize import QuantTensors


def _to_mem_hex(arr: np.ndarray) -> list[str]:
    """
    Convert INT8 values to two-digit hex strings for Verilog $readmemh.

    Example: np.array([63, -94, 0], dtype=np.int8) → ["3F", "A2", "00"]
    """
    flat = arr.astype(np.int8).reshape(-1)
    return [f"{(int(v) & 0xFF):02X}" for v in flat]


def write_mem(path: Path, lines: list[str]) -> None:
    """
    Create parent dirs if needed and write one hex value per line.

    Example: write_mem(Path("weights.mem"), ["3F", "A2", "00"])
    creates a file:
        3F
        A2
        00
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def export_quant_tensors(
    q: QuantTensors,
    out_dir: Path,
    cfg: ModelConfig | None = None,
) -> tuple[Path, Path]:
    """
    Write concatenated weights.mem, biases.mem, and a small export_meta.txt.

    Layer matrices are flattened in order (FC0, FC1, ...) to match the RTL ROMs.
    Returns (weights_path, biases_path).
    """
    cfg = cfg or default_config()
    assert len(q.weights) == cfg.num_fc
    w_concat = np.concatenate(
        [w.reshape(-1) for w in q.weights], axis=0
    )  # concatenates all layers W
    b_concat = np.concatenate(
        [b.reshape(-1) for b in q.biases], axis=0
    )  # concatenates all layers bias
    w_path = out_dir / "weights.mem"
    b_path = out_dir / "biases.mem"
    write_mem(w_path, _to_mem_hex(w_concat))
    write_mem(b_path, _to_mem_hex(b_concat))
    meta = out_dir / "export_meta.txt"
    meta.write_text(
        "\n".join(
            [
                f"layer_sizes={list(cfg.layer_sizes)}",
                f"num_fc={cfg.num_fc}",
                f"binary={int(cfg.binary)}",
                f"frac_bits={q.frac_bits}",
                f"weight_bytes={w_concat.size}",
                f"bias_bytes={b_concat.size}",
                f"weight_scales={q.weight_scales}",
            ]
        )
        + "\n",
        encoding="utf-8",
    )
    return w_path, b_path


def render_params_vh(cfg: ModelConfig) -> str:
    """
    Build the text of verilog header (rtl/include/fnn_params.vh) from ModelConfig.

    Includes bit-widths, layer sizes, weight/bias base addresses, and MMIO map.
    Unused layer slots are filled with zeros up to max_layers.
    Every define carries an explanatory comment; numbers inside comments are
    derived from cfg so they stay correct for any topology.
    """
    max_w = cfg.max_width()
    act_aw = cfg.act_addr_w()
    w_depth = cfg.weight_count()
    b_depth = cfg.bias_count()
    w_aw = cfg.w_addr_w()
    w_bases = cfg.weight_bases()
    b_bases = cfg.bias_bases()
    sizes = cfg.layer_sizes

    binary_txt = (
        "binary-output classification mode (0 and 1)"
        if cfg.binary
        else "multi-valued (non-binary) output mode"
    )

    lines = [
        '// Auto-generated by sw/model/export_weights.py — DO NOT EDIT.',
        '// Re-run "make deploy" after changing layer sizes in software side.',
        "",
        "`ifndef FNN_PARAMS_VH   // Check whether the macro FNN_PARAMS_VH has already been defined.",
        "`define FNN_PARAMS_VH   // define it",
        "",
        "// Data representation parameters",
        f"`define FNN_DATA_W      {cfg.data_width}  // The width of each neural network input and weight is {cfg.data_width} bits.",
        "`define FNN_ACC_W       32 // The accumulator width is 32 bits. 32-bit accumulator prevents overflow when summing multiple 8-bit multiplication results.",
        f"`define FNN_FRAC_BITS   {cfg.frac_bits} // This specifies the number of fractional bits used in the fixed-point representation.",
        "`define FNN_BIAS_W      8 // Each bias is stored using 8 bits.",
        f"`define FNN_NUM_PE      {cfg.num_pe} // {cfg.num_pe} processing elements (PEs).It performs operations such as multiplication and accumulation.",
        "",
        "// Neural network architecture",
        f"`define FNN_NUM_FC      {cfg.num_fc} // {cfg.num_fc} fully-connected layers. Input layer is not counted as fully-connected",
        f"`define FNN_MAX_LAYERS  {cfg.max_layers} // The hardware supports a maximum of {cfg.max_layers} FC layers.",
        f"`define FNN_INPUT_DIM   {cfg.input_dim} // The network accepts {cfg.input_dim} input features",
        f"`define FNN_OUTPUT_DIM  {cfg.output_dim} // The network gives {cfg.output_dim} output value{'s' if cfg.output_dim != 1 else ''}",
        f"`define FNN_BINARY_OUT  {1 if cfg.binary else 0} // The network uses {binary_txt}.",
        f"`define FNN_MAX_WIDTH   {max_w} // The maximum supported layer width is {max_w} neurons.",
        f"`define FNN_MAX_IN      {max_w} // The maximum number of inputs accepted by a layer is {max_w}.",
        f"`define FNN_MAX_OUT     {max_w} // The maximum number of outputs produced by a layer is {max_w}.",
        f"`define FNN_ACT_ADDR_W  {act_aw} // This specifies a {act_aw}-bit address width for activation memory addressing. "
        f"A {act_aw}-bit address can represent: {2 ** act_aw} different addresses (sufficient for {max_w} activation values)",
        f"`define FNN_W_DEPTH     {w_depth} // The total number of weight entries required by the network.",
        f"`define FNN_B_DEPTH     {b_depth} // The total number of bias entries",
        f"`define FNN_W_ADDR_W    {w_aw} // weight memory address width is {w_aw} bits.",
        "",
        "// Per-layer geometry",
        "// Each FC layer has its own input and output dimensions (in[i] -> out[i]).",
        "// Unused slots are represented as 0",
    ]

    # Per-layer loop
    for i in range(cfg.max_layers):
        if i < cfg.num_fc:
            lin, lout = sizes[i], sizes[i + 1]
            wb, bb = w_bases[i], b_bases[i]
        else:
            lin = lout = wb = bb = 0
        w_cmt = (
            f" // The first layer's weights start at memory address {wb}"
            if i == 0
            else ""
        )
        b_cmt = (
            f" // The first layer's biases start at bias memory address {bb}."
            if i == 0
            else ""
        )
        lines += [
            f"`define FNN_L{i}_IN      {lin}",
            f"`define FNN_L{i}_OUT     {lout}",
            f"`define FNN_W_BASE_{i}   {wb}{w_cmt}",
            f"`define FNN_B_BASE_{i}   {bb}{b_cmt}",
        ]

    # MMIO map: fixed register addresses for the AXI host.
    lines += [
        "",
        "// Hardware control registers: the addresses of registers used for communication between PS and PL.",
        "`define FNN_REG_CTRL    8'h00 // Control commands, such as starting the accelerator",
        "`define FNN_REG_STATUS  8'h04 // Indicates whether the accelerator is busy or finished",
        "`define FNN_REG_FEAT_W  8'h08 // Feature/input-related configuration",
        "`define FNN_REG_ADDR    8'h0C // Address selection for data access",
        "`define FNN_REG_DATA    8'h10 // Data register for reading or writing",
        "`define FNN_REG_PRED    8'h14 // Prediction result",
        "`define FNN_REG_CYCLES  8'h18 // Number of execution cycles",
        "",
        "`endif // This closes the conditional block.",
        "",
    ]
    return "\n".join(lines)


def write_params_vh(cfg: ModelConfig, path: Path = PARAMS_VH) -> None:
    """Write fnn_params.vh so the RTL matches the current model shape."""
    path.write_text(render_params_vh(cfg), encoding="utf-8")


def main() -> None:
    """CLI: regenerate fnn_params.vh; optional --layers to set topology."""
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--patch-vh", action="store_true", help="Regenerate fnn_params.vh")
    p.add_argument(
        "--layers",
        type=str,
        default="",
        help="Comma-separated layer sizes, e.g. 10,6,1 or 10,64,32,1",
    )
    args = p.parse_args()
    if args.layers:
        sizes = tuple(int(x) for x in args.layers.split(","))
        from .config import with_layers

        cfg = with_layers(sizes)
    else:
        cfg = default_config()
    if args.patch_vh:
        write_params_vh(cfg)
        print(f"Wrote {PARAMS_VH} for {cfg.layer_sizes}")
    else:
        p.print_help()


if __name__ == "__main__":
    main()

#!/usr/bin/env python3
"""CI helper: write tiny INT8 ROMs + golden vectors without the UNSW CSVs."""

from __future__ import annotations

import numpy as np

from model.config import GENERATED_DIR, REPO_ROOT, with_layers
from model.export_weights import export_quant_tensors, write_params_vh
from model.quantize import QuantTensors, sw_int_forward


def main() -> None:
    cfg = with_layers((10, 6, 1))
    rng = np.random.default_rng(0)

    weights = [
        rng.integers(-64, 65, size=(6, 10), dtype=np.int8),
        rng.integers(-64, 65, size=(1, 6), dtype=np.int8),
    ]
    biases = [
        rng.integers(-32, 33, size=(6,), dtype=np.int8),
        rng.integers(-32, 33, size=(1,), dtype=np.int8),
    ]
    q = QuantTensors(
        weights=weights,
        biases=biases,
        weight_scales=[2**-7] * cfg.num_fc,
        act_scale=2**-7,
        frac_bits=cfg.frac_bits,
    )

    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    export_quant_tensors(q, GENERATED_DIR, cfg)
    write_params_vh(cfg)

    n = 50
    feat_lines: list[str] = []
    exp_lines: list[str] = []
    label_lines: list[str] = []
    for _ in range(n):
        x_q = rng.integers(-64, 65, size=(cfg.input_dim,), dtype=np.int8)
        _, pred = sw_int_forward(q, x_q)
        # Synthetic stand-in labels (not UNSW); TB still reports "accuracy"
        label = int(rng.integers(0, 2))
        feat_lines.extend(f"{(int(v) & 0xFF):02X}" for v in x_q)
        exp_lines.append(f"{pred:02X}")
        label_lines.append(f"{label:02X}")

    out = REPO_ROOT / "sim" / "golden"
    out.mkdir(parents=True, exist_ok=True)
    (out / "features.mem").write_text("\n".join(feat_lines) + "\n", encoding="utf-8")
    (out / "expected.mem").write_text("\n".join(exp_lines) + "\n", encoding="utf-8")
    (out / "labels.mem").write_text("\n".join(label_lines) + "\n", encoding="utf-8")
    (out / "golden_params.vh").write_text(
        "\n".join(
            [
                "// Auto-generated by scripts/ci_smoke_export.py",
                f"`define GOLDEN_N_SAMPLES  {n}",
                f"`define GOLDEN_FEAT_WORDS {n * cfg.input_dim}",
                "",
            ]
        ),
        encoding="utf-8",
    )
    print(f"CI smoke export: {n} random samples → {GENERATED_DIR} + {out}")


if __name__ == "__main__":
    main()
